const manifest=()=>({schema:'tavi.extension/v1',id:'org.tavi.demo.settings',version:'1.0.0',name:'Demo Preferences',summary:'Fixture',publisher:'tavi',kind:'app',hostApi:{min:'1.0.0',maxExclusive:'2.0.0'},entrypoints:{panel:'ui/index.html'},contributions:[{slot:'settings.app',id:'preferences',label:'Manage appearance',action:'openPanel'}],permissions:['ui.panel']});
test('one declarative Settings link is supported by TaviX v1, without injecting a host UI',()=>{
 const m=manifest();assert(validateExtensionManifest(m).compatible);
 const duplicate=structuredClone(m);duplicate.contributions.push({...m.contributions[0],id:'another'});
 assert.throws(()=>validateExtensionManifest(duplicate),/Only one settings entry/);
 const other=structuredClone(m);other.contributions[0].action='updateHostSettings';
 assert.throws(()=>validateExtensionManifest(other),/Unsupported contribution/);
 const payload=structuredClone(m);payload.contributions[0].label='<script>bad</script>';
 const storage=memory(),scope=extensionStorageScope('https://social.example','alice');
 const store=createExtensionStore({storage,scope});store.install(payload);
 const rows=extensionSettingsEntries([{manifest:payload}],store,{platform:'windows'});
 assert.equal(rows.length,1);
 const html=renderSettings({page:'extensions',repositories:[],appSettings:rows});
 assert.match(html,/data-settings-extension="org.tavi.demo.settings"/);
 assert.doesNotMatch(html,/<script>bad<\/script>/);
 assert.match(html,/&lt;script&gt;bad&lt;\/script&gt;/);
});
test('contributed links require a live installed enabled same-version same-source package',()=>{
 const storage=memory(),m=manifest(),origin='https://social.example',one=extensionStorageScope(origin,'one'),two=extensionStorageScope(origin,'two');
 const store=createExtensionStore({storage,scope:one}),other=createExtensionStore({storage,scope:two});
 const bundle={manifest:m};
 assert.deepEqual(extensionSettingsEntries([bundle],store),[]);
 store.install(m);assert.equal(extensionSettingsEntries([bundle],store).length,1);
 const edited=structuredClone(m);edited.contributions[0].label='Changed by publisher';
 assert.equal(extensionSettingsEntries([{manifest:edited}],store)[0].label,'Manage appearance','Unapproved metadata edits never change the settings directory');
 assert.equal(extensionSettingsEntries([bundle],other).length,0);
 store.disable(m.id);assert.equal(extensionSettingsEntries([bundle],store).length,0);
 store.enable(m);assert.equal(extensionSettingsEntries([bundle],store).length,1);
 const version=structuredClone(m);version.version='1.0.1';
 assert.equal(extensionSettingsEntries([{manifest:version}],store).length,0);
 const remote={manifest:m,repositoryUrl:'https://publisher.example/catalog.json'};
 assert.equal(extensionSettingsEntries([remote],store).length,0);
 store.uninstall(m.id);store.install(m,remote.repositoryUrl);
 assert.equal(extensionSettingsEntries([remote],store).length,1);
 assert.equal(extensionSettingsEntries([remote],store,{platform:'windows'}).length,1);
 const androidOnly=structuredClone(m);androidOnly.platforms=['android'];
 store.uninstall(m.id);store.install(androidOnly,remote.repositoryUrl);
 assert.equal(extensionSettingsEntries([{manifest:androidOnly,repositoryUrl:remote.repositoryUrl}],store,{platform:'windows'}).length,0);
 assert.equal(extensionSettingsEntries([{manifest:androidOnly,repositoryUrl:remote.repositoryUrl}],store,{platform:'android'}).length,1);
});
