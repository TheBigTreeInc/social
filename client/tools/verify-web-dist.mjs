import {readFile, stat, readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import assert from 'node:assert/strict';
const client=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const file=p=>resolve(client,'dist',p);
const entry=await readFile(file('index.html'),'utf8');
assert(entry.includes('src="./assets/') || entry.includes('src="/assets/'), 'Vite entrypoint missing');
assert(!entry.includes('https://social.example.org'), 'Do not hardcode user server endpoint');
const chat=await readFile(file('chat.html'),'utf8');
assert(chat.includes('src="./assets/')||chat.includes('src="/assets/'),'Separate chat entrypoint missing from static distribution');
const portrait=await readFile(file('portrait/index.html'),'utf8');
assert(!portrait.includes('src="/portrait/') && !portrait.includes('href="/portrait/'), 'Portrait workshop must support subpath hosting');
for(const p of ['portrait/workshop.js','portrait/portrait.css','social-client-manifest.json','sdk/looprd-social.js']) await stat(file(p));
const metadata=JSON.parse(await readFile(file('social-client-manifest.json'),'utf8'));
const sdk=await readFile(file(metadata.entry));
assert.equal(createHash('sha256').update(sdk).digest('hex'),metadata.sha256);
assert.equal(metadata.schema,'looprd.social.browser-sdk/v1');
assert.equal(metadata.clientVersion,JSON.parse(await readFile(resolve(client,'package.json'),'utf8')).version);
assert.equal((await readFile(resolve(client,'sdk/looprd-social.js'))).compare(sdk),0,'Native/browser SDK source mismatch');
assert((await readdir(file('assets'))).some(p=>p.endsWith('.js')),'Compiled web JS missing');
console.log('Static web distribution and identical browser/native SDK verified.');
