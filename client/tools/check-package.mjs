import {readFile,stat} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const here=dirname(fileURLToPath(import.meta.url));
const root=resolve(here,'../..'),client=resolve(root,'client');
const read=async path=>JSON.parse(await readFile(resolve(root,path),'utf8'));
import {syncInternalExtensions} from '../../tools/sync-internal-extensions.mjs';
const internal=await syncInternalExtensions({check:true});
assert(internal.count>=2);
const board=await read('.ziprunner-workboard-update.json');
assert.equal(board.schema,'ziprunner.workboard-update.v1');
assert.equal(board.project,'looprd-social');
assert(board.implemented.length);
const ids=[...board.implemented,...board.remaining].map(x=>x.id);
assert.equal(new Set(ids).size,ids.length);
const recipe=await read('project.zr');
assert.equal(recipe.schema,'ziprunner.zr/v1');
assert.equal(recipe.project_key,board.project);
assert(recipe.match.includes('looprd-social-*-ziprunner.zip'));
const manifest=await read('ziprunner-manifest.json');
assert.equal(manifest.project.key,board.project);
assert.equal(manifest.project.version,board.version);
const pkg=await read('package.json');assert.equal(pkg.version,board.version);
const link=await read('ziprunner.looprd.json');assert.equal(link.schema,'ziprunner.looprd-link/v1');assert.equal(link.project,board.project);assert.equal(link.component,board.project);
const descriptor=await readFile(resolve(root,link.specification));
assert(!descriptor.includes(13), 'LoopRD descriptor must retain LF line endings for the byte-exact ZipRunner SHA-256 link; check .gitattributes and Git checkout settings.');
assert.equal(link.specification_sha256,createHash('sha256').update(descriptor).digest('hex'));
const clientPkg=await read('client/package.json');assert.equal(clientPkg.name,'looprd-social-client');
const lock=await read('client/portrait-source.lock.json');assert.equal(lock.repository,'TheBigTreeInc/assets');
for(const path of ['client/chat.html','client/game.html','client/src/game.js','client/src/game.css','client/src-tauri/capabilities/games.json','docs/GAME_CATALOG.adoc','client/vite.config.mjs','client/src/chat.js','client/src/chat.css','client/src/native-windows.js','client/src-tauri/capabilities/conversations.json','looprd.yaml','server/looprd_handler.py','tools/generate-looprd.py','client/src/main.js','client/src/device-session.js','client/src-tauri/src/lib.rs','client/src/protocol.js','client/sdk/looprd-social.js','docs/DESIGN.adoc','docs/JAVASCRIPT_CLIENT.adoc','.github/workflows/web.yml','client/tools/emit-browser-sdk.mjs','client/tools/verify-web-dist.mjs','client/src/notifications.js','client/public/portrait/index.html','client/src-tauri/tauri.conf.json','.github/workflows/windows.yml','.github/workflows/android.yml','.github/workflows/portrait-updates.yml','client/docs/GAME_ACTIVITY_CONTRACT.md']) await stat(resolve(root,path));
console.log('Integrated Social server/client recipe, package and manifest are consistent.');
